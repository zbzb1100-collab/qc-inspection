// 照片刪除：不再有 ×，要點開大圖按兩次刪除；刪除先標記、可復原，儲存才真的刪
import { createRequire } from 'module';
import fs from 'fs';
const require = createRequire('/opt/node22/lib/node_modules/');
const { chromium } = require('playwright');
const root = new URL('..', import.meta.url).pathname;
const mock = fs.readFileSync(root + 'dev/mock-supabase.js', 'utf8');
const results = []; const fail = [];
const ok = (c, m) => { results.push((c ? 'PASS ' : 'FAIL ') + m); if (!c) fail.push(m); };
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--no-sandbox'] });
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 } })).newPage(); const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.addInitScript(mock);
await page.addInitScript(() => {
  const T = window.__db.T; T.inspect_types[0].need_sign = true;
  const base = { site_id: 1, inspect_type_id: 1, building_id: 1, floor: '8F', unit_id: 1, space_id: 2, category_id: 1, item_id: 1, fix_vendor_id: 1, resp_vendor_id: 1,
    created_by: 'u-staff', created_at: '2026-10-01T00:00:00Z', updated_at: '2026-10-01T00:00:00Z', signed_name: null, signed_date: null };
  T.defects.push({ id: 1, ...base, status: 'fixed', description: 'a' }, { id: 2, ...base, status: 'signing', description: 'b' }, { id: 3, ...base, status: 'signing', description: 'c' });
  T.defect_photos.push({ id: 1, defect_id: 1, kind: 'after', path: '1/a.jpg', created_by: 'u-staff' });
});
await page.route('**/*', r => { const u = r.request().url(); if (u.startsWith('file://')) return r.continue(); if (u.includes('xlsx') || u.includes('supabase')) return r.fulfill({ contentType: 'application/javascript', body: '' }); return r.fulfill({ contentType: 'text/css', body: '' }); });
await page.goto('file://' + root + 'index.html');
await page.fill('#l-email', 'staff@x.com'); await page.fill('#l-pass', 'pw'); await page.click('#l-go');
await page.waitForSelector('#app:not([hidden])');
await page.click('#floor .chip:has-text("8F")'); await page.click('#units button:has-text("A1")'); await page.click('#go');
await page.waitForSelector('#dlist .item');
await page.locator('#dlist .item').nth(0).click(); await page.waitForSelector('#sheet:not([hidden])'); await page.waitForTimeout(300);
ok(await page.locator('#sh-afterphotos .ph button').count() === 0, '照片上沒有 × 刪除鍵');
await page.click('#sh-afterphotos .ph img'); await page.waitForSelector('#viewer:not([hidden])');
ok(await page.locator('#viewer-del').isVisible(), '大圖畫面有刪除鈕');
await page.click('#viewer-del'); await page.waitForTimeout(100);
ok(await page.locator('#viewer').isVisible() && (await page.textContent('#viewer-del')).includes('再按一次'), '刪除要按兩次');
await page.click('#viewer-close'); await page.waitForTimeout(100);
ok(await page.locator('#sh-afterphotos .ph.del').count() === 0, '按關閉不會刪');
await page.click('#sh-afterphotos .ph img'); await page.click('#viewer-del'); await page.click('#viewer-del'); await page.waitForTimeout(100);
ok(await page.locator('#sh-afterphotos .ph.del').count() === 1, '刪除後先標記待刪除');
await page.click('#sh-afterphotos .ph .undo'); await page.waitForTimeout(100);
ok(await page.locator('#sh-afterphotos .ph.del').count() === 0, '點一下可以復原');
await page.click('#sh-afterphotos .ph img'); await page.click('#viewer-del'); await page.click('#viewer-del');
await page.click('#sh-cancel'); await page.waitForTimeout(200);
let P = await page.evaluate(() => window.__db.T.defect_photos.length);
ok(P === 1, '按取消不會真的刪');
await page.locator('#dlist .item').nth(0).click(); await page.waitForSelector('#sheet:not([hidden])'); await page.waitForTimeout(300);
await page.click('#sh-afterphotos .ph img'); await page.click('#viewer-del'); await page.click('#viewer-del');
await page.click('#sh-pass'); await page.waitForTimeout(300);
P = await page.evaluate(() => window.__db.T.defect_photos.filter(p => !p.deleted_at).length);
ok(P === 0, '按下動作後才標記刪除（軟刪除，紀錄保留）');
ok(errors.length === 0, 'JS 錯誤：' + errors.join('|'));
console.log(results.join('\n')); await browser.close(); process.exit(fail.length ? 1 : 0);
