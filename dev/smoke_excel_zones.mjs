const p5 = '/tmp/claude-0/xl/zin2.xlsx'; XLSX.writeFile(wb4, p5);
await page.locator('#xl-file').setInputFiles(p5); await page.waitForSelector('#xl-go'); await page.click('#xl-go'); await page.waitForTimeout(800);
